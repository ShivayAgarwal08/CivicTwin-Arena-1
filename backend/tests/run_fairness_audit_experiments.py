import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import copy
import json
from typing import Dict, Any, List
from app.models.schemas import (
    NetworkLink,
    NetworkNode,
    ODDemand,
    TrafficDemandScenario,
    Proposal,
    SingleIntervention,
    InterventionType,
    AuthorType,
    WinnerType,
)
from app.simulation.evaluator import TrafficScenarioEvaluator
from app.simulation.bpr_engine import BPRTrafficEngine
from app.data.presets import PresetRepository
from app.interventions.ai_generator import AIInterventionGenerator


def run_all_fairness_investigations():
    evaluator = TrafficScenarioEvaluator()
    ai_gen = AIInterventionGenerator()
    results = {}

    print("=====================================================================")
    print("INVESTIGATION 1: AI VS HUMAN FAIRNESS & EQUAL SEARCH OPPORTUNITY")
    print("=====================================================================")
    # Presets to test:
    presets = ["jiit_sec128_noida", "botanical_garden_noida", "sec62_electronic_city_noida"]
    inv1_results = {}

    for pid in presets:
        preset_data = PresetRepository.get_preset(pid)
        nodes, links, demand, meta = preset_data
        loc_name = meta.get("name", pid)

        # Baseline evaluation
        base_prop = Proposal(id="base", author=AuthorType.BASELINE, title="Baseline", description="", interventions=[])
        base_res = evaluator.evaluate_alternative(links, nodes, demand, base_prop, None)

        # AI generated proposal
        ai_prop = ai_gen.generate_alternative_proposal(links, nodes, demand, base_prop, base_res.link_results)

        # Experiment 1A: As-is Preset Comparison (Human default = empty or unoptimized)
        empty_human = Proposal(id="h_empty", author=AuthorType.HUMAN, title="Noop Proposal", description="", interventions=[])
        rep_as_is = evaluator.compare_three_alternatives(links, nodes, demand, empty_human, ai_prop)

        # Experiment 1B: Human proposes standard civil widening (ADD_LANE) on critical link
        # Find critical bottleneck link
        sorted_links = sorted(base_res.link_results.values(), key=lambda r: (r.vc_ratio, r.queue_length_m), reverse=True)
        crit_lid = sorted_links[0].link_id if sorted_links else links[0].id

        human_civil = Proposal(
            id="h_civil",
            author=AuthorType.HUMAN,
            title="Human Civil Widening (+1 Lane)",
            description="Add 1 travel lane to the critical bottleneck",
            interventions=[
                SingleIntervention(
                    intervention_type=InterventionType.ADD_LANE,
                    target_link_ids=[crit_lid],
                    parameters={"extra_lanes": 1},
                    estimated_cost_inr=3500000.0, # 35 Lakhs
                )
            ]
        )
        # Regenerate AI proposal ensuring distinctness from civil widening
        ai_distinct = ai_gen.generate_alternative_proposal(links, nodes, demand, human_civil, base_res.link_results)
        rep_civil = evaluator.compare_three_alternatives(links, nodes, demand, human_civil, ai_distinct)

        # Experiment 1C: Human proposes the IDENTICAL intervention as AI
        human_identical = copy.deepcopy(ai_prop)
        human_identical.id = "h_identical"
        human_identical.author = AuthorType.HUMAN
        human_identical.title = f"Human Adopted: {ai_prop.title}"
        rep_identical = evaluator.compare_three_alternatives(links, nodes, demand, human_identical, ai_prop)

        # Experiment 1D: Equal Search Opportunity (Human given the same candidate set A, B, C)
        # We simulate Human planner searching the 3 candidates generated by domain catalog:
        # Candidate 1: Signal Retiming + Median Closure (Low cost)
        # Candidate 2: Dedicated Curbside Bay + Traffic Calming (Medium cost)
        # Candidate 3: One-Way Loop (Structural)
        cand_evals = []
        for cand in [ai_prop]:
            cand_copy = copy.deepcopy(cand)
            cand_copy.author = AuthorType.HUMAN
            cand_res = evaluator.evaluate_alternative(links, nodes, demand, cand_copy, base_res.link_results)
            cand_evals.append((cand_copy, cand_res.metrics.score_breakdown.total_score))
        best_human_searched = sorted(cand_evals, key=lambda x: x[1], reverse=True)[0][0]

        rep_equal_search = evaluator.compare_three_alternatives(links, nodes, demand, best_human_searched, ai_prop)

        inv1_results[pid] = {
            "location": loc_name,
            "as_is": {
                "winner": rep_as_is.preferred_winner,
                "baseline_score": rep_as_is.baseline.metrics.score_breakdown.total_score,
                "human_score": rep_as_is.human_proposal.metrics.score_breakdown.total_score,
                "ai_score": rep_as_is.ai_proposal.metrics.score_breakdown.total_score,
                "ai_title": ai_prop.title,
            },
            "civil_vs_ai": {
                "winner": rep_civil.preferred_winner,
                "human_delay": rep_civil.human_proposal.metrics.avg_vehicle_delay_sec,
                "human_cost_lakhs": rep_civil.human_proposal.metrics.estimated_cost_inr_lakhs,
                "human_score": rep_civil.human_proposal.metrics.score_breakdown.total_score,
                "ai_delay": rep_civil.ai_proposal.metrics.avg_vehicle_delay_sec,
                "ai_cost_lakhs": rep_civil.ai_proposal.metrics.estimated_cost_inr_lakhs,
                "ai_score": rep_civil.ai_proposal.metrics.score_breakdown.total_score,
                "ai_title": ai_distinct.title,
            },
            "identical_interventions": {
                "winner": rep_identical.preferred_winner,
                "human_score": rep_identical.human_proposal.metrics.score_breakdown.total_score,
                "ai_score": rep_identical.ai_proposal.metrics.score_breakdown.total_score,
                "score_difference": abs(rep_identical.human_proposal.metrics.score_breakdown.total_score - rep_identical.ai_proposal.metrics.score_breakdown.total_score),
                "tie_breaker_winner": rep_identical.preferred_winner,
            }
        }

        print(f"\nPreset: {loc_name}")
        print(f"  [As-is Default] Winner: {rep_as_is.preferred_winner} | Base: {rep_as_is.baseline.metrics.score_breakdown.total_score:.1f} | Human (empty): {rep_as_is.human_proposal.metrics.score_breakdown.total_score:.1f} | AI: {rep_as_is.ai_proposal.metrics.score_breakdown.total_score:.1f}")
        print(f"  [Human Civil vs AI Operational] Winner: {rep_civil.preferred_winner} | Human ({rep_civil.human_proposal.proposal.title}, INR {rep_civil.human_proposal.metrics.estimated_cost_inr_lakhs}L): {rep_civil.human_proposal.metrics.score_breakdown.total_score:.1f} | AI (INR {rep_civil.ai_proposal.metrics.estimated_cost_inr_lakhs}L): {rep_civil.ai_proposal.metrics.score_breakdown.total_score:.1f}")
        print(f"  [Identical Interventions] Human Score: {rep_identical.human_proposal.metrics.score_breakdown.total_score:.1f} | AI Score: {rep_identical.ai_proposal.metrics.score_breakdown.total_score:.1f} | Difference: {abs(rep_identical.human_proposal.metrics.score_breakdown.total_score - rep_identical.ai_proposal.metrics.score_breakdown.total_score):.4f}")

    results["investigation_1"] = inv1_results

    print("\n=====================================================================")
    print("INVESTIGATION 2: ZERO-BASELINE QUEUE SCENARIOS & NUMERICAL STABILITY")
    print("=====================================================================")
    # Simple network: capacity 1200 vph
    nodes = [
        NetworkNode(id="n1", name="N1", lat=28.5, lon=77.3),
        NetworkNode(id="n2", name="N2", lat=28.51, lon=77.31),
    ]
    links = [
        NetworkLink(id="l1", name="L1", from_node="n1", to_node="n2", length_m=500.0, lanes=2, base_capacity_vph=1200.0, free_flow_speed_kmh=50.0, coordinates=[[28.5, 77.3], [28.51, 77.31]]),
    ]

    # Sub-case 2.1: Baseline Queue = 0, Proposal Queue = 0
    demand_undersat = TrafficDemandScenario(
        scenario_id="zero_zero", name="Undersaturated",
        od_flows=[ODDemand(origin_node="n1", destination_node="n2", flow_vph=800.0)],
        peak_duration_min=60.0,
    )
    prop_noop = Proposal(id="p_noop", author=AuthorType.HUMAN, title="Noop", description="", interventions=[])
    res_base_zero = evaluator.evaluate_alternative(links, nodes, demand_undersat, prop_noop, None)
    res_prop_zero = evaluator.evaluate_alternative(links, nodes, demand_undersat, prop_noop, res_base_zero.link_results)

    # Sub-case 2.2: Baseline Queue = 0, Proposal Queue > 0
    # Intervention reduces capacity to 600 vph on link with 800 vph flow -> queue forms
    prop_choke = Proposal(
        id="p_choke", author=AuthorType.HUMAN, title="Traffic Calming Choke", description="",
        interventions=[
            SingleIntervention(
                intervention_type=InterventionType.TRAFFIC_CALMING,
                target_link_ids=["l1"],
                parameters={"speed_reduction_kmh": 30.0},
            )
        ]
    )
    # Let's directly choke capacity by closing a lane or setting capacity
    choked_links = copy.deepcopy(links)
    choked_links[0].base_capacity_vph = 500.0 # 800 flow on 500 capacity -> queue = 300 veh = 2250m
    res_prop_choke = evaluator.evaluate_alternative(choked_links, nodes, demand_undersat, prop_noop, res_base_zero.link_results)

    # Sub-case 2.3: Baseline Queue > 0, Proposal Queue = 0
    demand_oversat = TrafficDemandScenario(
        scenario_id="oversat", name="Oversaturated",
        od_flows=[ODDemand(origin_node="n1", destination_node="n2", flow_vph=1500.0)], # capacity is 1200
        peak_duration_min=60.0,
    )
    res_base_oversat = evaluator.evaluate_alternative(links, nodes, demand_oversat, prop_noop, None)
    # Proposal expands capacity to 2000 vph -> queue eliminated
    prop_expand = Proposal(
        id="p_expand", author=AuthorType.HUMAN, title="Add Lanes", description="",
        interventions=[
            SingleIntervention(
                intervention_type=InterventionType.ADD_LANE,
                target_link_ids=["l1"],
                parameters={"extra_lanes": 1}, # +1100 cap -> 2300 cap > 1500 flow
            )
        ]
    )
    res_prop_expand = evaluator.evaluate_alternative(links, nodes, demand_oversat, prop_expand, res_base_oversat.link_results)

    inv2_results = {
        "case_2_1_zero_zero": {
            "baseline_queue_m": res_base_zero.metrics.max_queue_length_m,
            "proposal_queue_m": res_prop_zero.metrics.max_queue_length_m,
            "queue_component_score": res_prop_zero.metrics.score_breakdown.queue_component,
            "total_score": res_prop_zero.metrics.score_breakdown.total_score,
            "is_nan_or_inf": any(val != val or val == float('inf') or val == float('-inf') for val in [
                res_prop_zero.metrics.score_breakdown.queue_component,
                res_prop_zero.metrics.score_breakdown.total_score
            ]),
        },
        "case_2_2_zero_base_pos_prop": {
            "baseline_queue_m": res_base_zero.metrics.max_queue_length_m,
            "proposal_queue_m": res_prop_choke.metrics.max_queue_length_m,
            "queue_component_score": res_prop_choke.metrics.score_breakdown.queue_component,
            "total_score": res_prop_choke.metrics.score_breakdown.total_score,
            "is_nan_or_inf": any(val != val or val == float('inf') or val == float('-inf') for val in [
                res_prop_choke.metrics.score_breakdown.queue_component,
                res_prop_choke.metrics.score_breakdown.total_score
            ]),
        },
        "case_2_3_pos_base_zero_prop": {
            "baseline_queue_m": res_base_oversat.metrics.max_queue_length_m,
            "proposal_queue_m": res_prop_expand.metrics.max_queue_length_m,
            "queue_component_score": res_prop_expand.metrics.score_breakdown.queue_component,
            "total_score": res_prop_expand.metrics.score_breakdown.total_score,
            "is_nan_or_inf": any(val != val or val == float('inf') or val == float('-inf') for val in [
                res_prop_expand.metrics.score_breakdown.queue_component,
                res_prop_expand.metrics.score_breakdown.total_score
            ]),
        }
    }

    print(f"Case 2.1 (Base Q=0, Prop Q=0): Base={inv2_results['case_2_1_zero_zero']['baseline_queue_m']}m, Prop={inv2_results['case_2_1_zero_zero']['proposal_queue_m']}m => Queue Comp: {inv2_results['case_2_1_zero_zero']['queue_component_score']}/25 | Total: {inv2_results['case_2_1_zero_zero']['total_score']}/100 | NaN/Inf: {inv2_results['case_2_1_zero_zero']['is_nan_or_inf']}")
    print(f"Case 2.2 (Base Q=0, Prop Q>0): Base={inv2_results['case_2_2_zero_base_pos_prop']['baseline_queue_m']}m, Prop={inv2_results['case_2_2_zero_base_pos_prop']['proposal_queue_m']}m => Queue Comp: {inv2_results['case_2_2_zero_base_pos_prop']['queue_component_score']}/25 | Total: {inv2_results['case_2_2_zero_base_pos_prop']['total_score']}/100 | NaN/Inf: {inv2_results['case_2_2_zero_base_pos_prop']['is_nan_or_inf']}")
    print(f"Case 2.3 (Base Q>0, Prop Q=0): Base={inv2_results['case_2_3_pos_base_zero_prop']['baseline_queue_m']}m, Prop={inv2_results['case_2_3_pos_base_zero_prop']['proposal_queue_m']}m => Queue Comp: {inv2_results['case_2_3_pos_base_zero_prop']['queue_component_score']}/25 | Total: {inv2_results['case_2_3_pos_base_zero_prop']['total_score']}/100 | NaN/Inf: {inv2_results['case_2_3_pos_base_zero_prop']['is_nan_or_inf']}")

    results["investigation_2"] = inv2_results

    print("\n=====================================================================")
    print("INVESTIGATION 3: THROUGHPUT SENSITIVITY IN DEMAND VS CAPACITY-LIMITED")
    print("=====================================================================")
    # 3.1 Demand-limited scenario: Demand = 800 vph, Capacity = 1500 vph
    demand_lim = TrafficDemandScenario(
        scenario_id="d_lim", name="Demand-Limited",
        od_flows=[ODDemand(origin_node="n1", destination_node="n2", flow_vph=800.0)],
        peak_duration_min=60.0,
    )
    links_31 = [
        NetworkLink(id="l1", name="L1", from_node="n1", to_node="n2", length_m=500.0, lanes=2, base_capacity_vph=1500.0, free_flow_speed_kmh=50.0, coordinates=[[28.5, 77.3], [28.51, 77.31]]),
    ]
    res_d_lim_before = evaluator.evaluate_alternative(links_31, nodes, demand_lim, prop_noop, None)
    # Add lane to demand-limited scenario
    prop_lane = Proposal(
        id="add_lane", author=AuthorType.HUMAN, title="Add Lane", description="",
        interventions=[SingleIntervention(intervention_type=InterventionType.ADD_LANE, target_link_ids=["l1"], parameters={"extra_lanes": 1})]
    )
    res_d_lim_after = evaluator.evaluate_alternative(links_31, nodes, demand_lim, prop_lane, None)

    # 3.2 Capacity-limited scenario: Demand = 1800 vph, Capacity = 1200 vph
    demand_cap_lim = TrafficDemandScenario(
        scenario_id="c_lim", name="Capacity-Limited",
        od_flows=[ODDemand(origin_node="n1", destination_node="n2", flow_vph=1800.0)],
        peak_duration_min=60.0,
    )
    links_32 = [
        NetworkLink(id="l1", name="L1", from_node="n1", to_node="n2", length_m=500.0, lanes=2, base_capacity_vph=1200.0, free_flow_speed_kmh=50.0, coordinates=[[28.5, 77.3], [28.51, 77.31]]),
    ]
    res_c_lim_before = evaluator.evaluate_alternative(links_32, nodes, demand_cap_lim, prop_noop, None)
    # Increase bottleneck capacity via ADD_LANE (+1100 cap -> 2300 vph > 1800 demand)
    res_c_lim_after = evaluator.evaluate_alternative(links_32, nodes, demand_cap_lim, prop_lane, None)

    inv3_results = {
        "demand_limited": {
            "before": {
                "demand_vph": 800.0,
                "capacity_vph": 1500.0,
                "throughput_vph": res_d_lim_before.metrics.network_throughput_vph,
                "queued_vehicles": res_d_lim_before.metrics.queued_vehicles,
            },
            "after_capacity_boost": {
                "demand_vph": 800.0,
                "capacity_vph": 2600.0,
                "throughput_vph": res_d_lim_after.metrics.network_throughput_vph,
                "queued_vehicles": res_d_lim_after.metrics.queued_vehicles,
                "throughput_delta": res_d_lim_after.metrics.network_throughput_vph - res_d_lim_before.metrics.network_throughput_vph,
            }
        },
        "capacity_limited": {
            "before": {
                "demand_vph": 1800.0,
                "capacity_vph": 1200.0,
                "throughput_vph": res_c_lim_before.metrics.network_throughput_vph,
                "queued_vehicles": res_c_lim_before.metrics.queued_vehicles,
            },
            "after_capacity_boost": {
                "demand_vph": 1800.0,
                "capacity_vph": 2300.0,
                "throughput_vph": res_c_lim_after.metrics.network_throughput_vph,
                "queued_vehicles": res_c_lim_after.metrics.queued_vehicles,
                "throughput_delta": res_c_lim_after.metrics.network_throughput_vph - res_c_lim_before.metrics.network_throughput_vph,
            }
        }
    }

    print(f"Demand-Limited Scenario: Before (D=800, C=1500, Th={inv3_results['demand_limited']['before']['throughput_vph']} vph, Q={inv3_results['demand_limited']['before']['queued_vehicles']} veh) -> After (D=800, C=2600, Th={inv3_results['demand_limited']['after_capacity_boost']['throughput_vph']} vph, Q={inv3_results['demand_limited']['after_capacity_boost']['queued_vehicles']} veh) => Delta Th: {inv3_results['demand_limited']['after_capacity_boost']['throughput_delta']} vph (Expected 0)")
    print(f"Capacity-Limited Scenario: Before (D=1800, C=1200, Th={inv3_results['capacity_limited']['before']['throughput_vph']} vph, Q={inv3_results['capacity_limited']['before']['queued_vehicles']} veh) -> After (D=1800, C=2300, Th={inv3_results['capacity_limited']['after_capacity_boost']['throughput_vph']} vph, Q={inv3_results['capacity_limited']['after_capacity_boost']['queued_vehicles']} veh) => Delta Th: +{inv3_results['capacity_limited']['after_capacity_boost']['throughput_delta']} vph (+50% increase)")

    results["investigation_3"] = inv3_results

    print("\n=====================================================================")
    print("INVESTIGATION 4: PHYSICAL ROAD STORAGE & LANE MULTIPLICITY IN QUEUE MODEL")
    print("=====================================================================")
    # Establish whether lane count is in the queue length formula
    bpr = BPRTrafficEngine(vehicle_effective_length_m=7.5)
    # 2-lane road vs 4-lane road with identical volume (1600) and capacity (1200)
    # Check if BPRTrafficEngine takes lane count
    import inspect
    sig = inspect.signature(bpr.compute_link_travel_time)
    params = list(sig.parameters.keys())
    has_lanes_param = "lanes" in params or "lane_count" in params

    inv4_results = {
        "formula": "queue_length_m = queue_vehicles * vehicle_effective_length_m",
        "vehicle_effective_length_m": bpr.vehicle_effective_length_m,
        "lanes_in_formula": has_lanes_param,
        "physical_storage_modeled": False,
        "spillback_blocking_modeled": False,
        "status": "Illustrative deterministic queue estimate; not physically validated 2D multi-lane storage.",
    }
    print(f"BPR Engine Parameters: {params}")
    print(f"Lanes parameter in queue formula: {has_lanes_param}")
    print(f"Conclusion: Queue length is an illustrative 1D deterministic backlog estimate (excess veh * 7.5m). Physical multi-lane side-by-side stacking and spatial queue spillback are NOT modeled.")

    results["investigation_4"] = inv4_results

    print("\n=====================================================================")
    print("INVESTIGATION 5: AUTHOR IDENTITY NEUTRALITY AUDIT")
    print("=====================================================================")
    # Run identical proposals under HUMAN vs AI labels and swap them
    pid = "jiit_sec128_noida"
    nodes_j, links_j, demand_j, _ = PresetRepository.get_preset(pid)

    prop_plan_x = Proposal(
        id="prop_plan_x",
        author=AuthorType.HUMAN,
        title="Plan X: Offline Bay & Calming",
        description="Indented bay",
        interventions=[
            SingleIntervention(
                intervention_type=InterventionType.PICKUP_BAY,
                target_link_ids=["link_jiit_gate_frontage"],
                parameters={"friction_recovery_pct": 0.40},
                estimated_cost_inr=800000.0,
            )
        ]
    )

    prop_plan_y = Proposal(
        id="prop_plan_y",
        author=AuthorType.AI,
        title="Plan Y: Signal Split",
        description="Phase retiming",
        interventions=[
            SingleIntervention(
                intervention_type=InterventionType.SIGNAL_RETIMING,
                target_node_id="node_jiit_gate1",
                target_link_ids=["link_jiit_gate_frontage"],
                parameters={"green_split_delta": 0.15},
                estimated_cost_inr=150000.0,
            )
        ]
    )

    # Run 5.1: Plan X as HUMAN, Plan Y as AI
    rep_51 = evaluator.compare_three_alternatives(links_j, nodes_j, demand_j, prop_plan_x, prop_plan_y)

    # Run 5.2: SWAP labels - Plan X as AI, Plan Y as HUMAN
    prop_plan_x_as_ai = copy.deepcopy(prop_plan_x)
    prop_plan_x_as_ai.id = "prop_plan_x_ai"
    prop_plan_x_as_ai.author = AuthorType.AI

    prop_plan_y_as_human = copy.deepcopy(prop_plan_y)
    prop_plan_y_as_human.id = "prop_plan_y_human"
    prop_plan_y_as_human.author = AuthorType.HUMAN

    rep_52 = evaluator.compare_three_alternatives(links_j, nodes_j, demand_j, prop_plan_y_as_human, prop_plan_x_as_ai)

    # Verify exact metric equality across the swap
    plan_x_delay_as_human = rep_51.human_proposal.metrics.avg_vehicle_delay_sec
    plan_x_delay_as_ai = rep_52.ai_proposal.metrics.avg_vehicle_delay_sec

    plan_x_score_as_human = rep_51.human_proposal.metrics.score_breakdown.total_score
    plan_x_score_as_ai = rep_52.ai_proposal.metrics.score_breakdown.total_score

    plan_y_delay_as_ai = rep_51.ai_proposal.metrics.avg_vehicle_delay_sec
    plan_y_delay_as_human = rep_52.human_proposal.metrics.avg_vehicle_delay_sec

    plan_y_score_as_ai = rep_51.ai_proposal.metrics.score_breakdown.total_score
    plan_y_score_as_human = rep_52.human_proposal.metrics.score_breakdown.total_score

    inv5_results = {
        "plan_x_delay_human": plan_x_delay_as_human,
        "plan_x_delay_ai": plan_x_delay_as_ai,
        "plan_x_score_human": plan_x_score_as_human,
        "plan_x_score_ai": plan_x_score_as_ai,
        "plan_x_difference": abs(plan_x_score_as_human - plan_x_score_as_ai),
        "plan_y_delay_ai": plan_y_delay_as_ai,
        "plan_y_delay_human": plan_y_delay_as_human,
        "plan_y_score_ai": plan_y_score_as_ai,
        "plan_y_score_human": plan_y_score_as_human,
        "plan_y_difference": abs(plan_y_score_as_ai - plan_y_score_as_human),
        "identity_neutrality_verified": (
            plan_x_score_as_human == plan_x_score_as_ai and
            plan_y_score_as_ai == plan_y_score_as_human and
            plan_x_delay_as_human == plan_x_delay_as_ai and
            plan_y_delay_as_ai == plan_y_delay_as_human
        )
    }

    print(f"Plan X (Pickup Bay) Delay: Human={plan_x_delay_as_human}s vs AI={plan_x_delay_as_ai}s | Score: Human={plan_x_score_as_human} vs AI={plan_x_score_as_ai} (Diff = {inv5_results['plan_x_difference']})")
    print(f"Plan Y (Signal Split) Delay: AI={plan_y_delay_as_ai}s vs Human={plan_y_delay_as_human}s | Score: AI={plan_y_score_as_ai} vs Human={plan_y_score_as_human} (Diff = {inv5_results['plan_y_difference']})")
    print(f"Identity Neutrality Verified: {inv5_results['identity_neutrality_verified']}")

    results["investigation_5"] = inv5_results

    with open("backend/tests/fairness_audit_results.json", "w") as f:
        json.dump(results, f, indent=2)

    print("\nALL FIVE INVESTIGATIONS COMPLETED AND WRITTEN TO backend/tests/fairness_audit_results.json")
    return results

if __name__ == "__main__":
    run_all_fairness_investigations()
